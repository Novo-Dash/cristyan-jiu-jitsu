// The blog (back on 13/11/2026, Adryan: "volta pro blog"): the 33 posts of the old site with their old slugs
// (/blog/<slug>), generated by scripts/blog.mjs. Each post keeps the photo it has on the old blog (only the three
// news posts carry one there); the others show a real academy photo picked by subject.

type Name = keyof typeof IMG
export const coverOf = (p: Post): Img => img((p.cover ?? 'mission') as Name, p.title)
const postHref = (p: Post) => `/blog/${p.slug}`
const NEWS = POSTS.filter((p) => p.category === 'News')
const CATS = ['All', ...new Set(POSTS.filter((p) => p.category !== 'News').map((p) => p.category))]

/** "The BJJ Belt System Explained: White to Black" → the part after the colon on the red band; else the last two words. */
const titleOf = (t: string): Title => {
  const c = t.indexOf(': ')
  if (c > 0) return { a: t.slice(0, c + 2), b: t.slice(c + 2) }
  const w = t.split(' ')
  return { a: `${w.slice(0, -2).join(' ')} `, b: w.slice(-2).join(' ') }
}

